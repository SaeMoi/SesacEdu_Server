-- 1. users ------------------------------------------------------------
CREATE TABLE users (
    user_id  NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    mail     VARCHAR2(255 CHAR) NOT NULL,                  -- 로그인 ID
    pw       VARCHAR2(255 CHAR) NOT NULL,                  -- MD5 hex (의도된 취약점)
    uname    VARCHAR2(50 CHAR)  NOT NULL,                  -- 실명
    nickname VARCHAR2(50 CHAR)  NOT NULL,                  -- 공개 표시명. UNIQUE 없음 (앱 검사만)
    token    CLOB,                                         -- 마지막으로 발급한 JWT. 없으면 NULL
    phone    VARCHAR2(20 CHAR),                            -- 공개 응답에 넣지 않는다
    b_date   DATE,
    address  VARCHAR2(500 CHAR),
    picture  VARCHAR2(500 CHAR),                           -- 프로필 이미지 파일명 {user_id}_profile.png
    alarm    NUMBER(1),                                    -- 알림 수신 설정
    auth     NUMBER(1)          DEFAULT 0 NOT NULL,        -- 0 일반/1 수강생/2 강사/3 관리자/4 강사 신청 대기
    status   VARCHAR2(20 CHAR)  DEFAULT 'active' NOT NULL, -- active / restricted
    created  TIMESTAMP          DEFAULT SYSTIMESTAMP,
    updated  TIMESTAMP,                                    -- 회원 정보 수정 시각
    CONSTRAINT pk_users        PRIMARY KEY (user_id),
    CONSTRAINT uq_users_mail   UNIQUE (mail),
    CONSTRAINT ck_users_auth   CHECK (auth IN (0, 1, 2, 3, 4)),
    CONSTRAINT ck_users_status CHECK (status IN ('active', 'restricted'))
);

-- 2. instructors (users 와 1:1) ---------------------------------------
--    approved_at·rejected_at 이 모두 NULL 이면 대기. 재신청은 같은 행을 갱신한다
CREATE TABLE instructors (
    user_id         NUMBER(19),
    iname           VARCHAR2(50 CHAR),                     -- 공개 강사명
    bio             VARCHAR2(200 CHAR),                    -- 한 줄 소개
    description     CLOB,                                  -- 공개 강사 소개 본문
    picture         VARCHAR2(500 CHAR),                    -- 공개 강사 프로필 이미지
    field           VARCHAR2(100 CHAR),
    career          CLOB,
    contact         VARCHAR2(500 CHAR),                    -- 공개 연락처 / 포트폴리오 링크
    career_file     VARCHAR2(500 CHAR),                    -- 증빙 서류 1개
    career_filename VARCHAR2(255 CHAR),                    -- 증빙 서류 원본 파일명
    bank            VARCHAR2(50 CHAR),                     -- 정산 은행
    account         VARCHAR2(50 CHAR),                     -- 정산 계좌
    applied_at      TIMESTAMP,
    approved_at     TIMESTAMP,
    rejected_at     TIMESTAMP,
    reject_reason   VARCHAR2(500 CHAR),
    updated         TIMESTAMP,
    CONSTRAINT pk_instructors      PRIMARY KEY (user_id),
    CONSTRAINT fk_instructors_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

-- 3. lectures ---------------------------------------------------------
--    강좌 1 : 영상 1 : 자료 1 : 과제 1. 내릴 때는 status = closed, 강제 삭제는 행 삭제
CREATE TABLE lectures (
    Lid                  NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    user_id              NUMBER(19)         NOT NULL,      -- 강사
    name                 VARCHAR2(200 CHAR) NOT NULL,
    headline             VARCHAR2(200 CHAR),               -- 강의 카드 한 줄 소개
    summary              CLOB,                             -- 강의 소개 본문
    category             VARCHAR2(50 CHAR)  NOT NULL,      -- 웹 보안/네트워크/개발 기초/로그 분석/클라우드
    lvl                  VARCHAR2(20 CHAR),                -- ERD level (예약어 회피). 입문/중급/고급
    picture              VARCHAR2(500 CHAR),               -- 썸네일
    preview              VARCHAR2(500 CHAR),               -- 공개 미리보기 영상
    video                VARCHAR2(500 CHAR),
    video_filename       VARCHAR2(255 CHAR),
    duration             NUMBER(10),                       -- 본 강의 영상 길이(초)
    material             VARCHAR2(500 CHAR),
    material_filename    VARCHAR2(255 CHAR),
    assignment_title     VARCHAR2(200 CHAR),
    assignment_content   CLOB,
    assignment_file_type VARCHAR2(100 CHAR),               -- 제출 허용 파일 형식 안내
    Lprice               NUMBER(10)         DEFAULT 0 NOT NULL,
    status               VARCHAR2(20 CHAR)  DEFAULT 'draft' NOT NULL,
    created              TIMESTAMP          DEFAULT SYSTIMESTAMP,
    updated              TIMESTAMP,
    CONSTRAINT pk_lectures        PRIMARY KEY (Lid),
    CONSTRAINT fk_lectures_inst   FOREIGN KEY (user_id) REFERENCES instructors (user_id),
    CONSTRAINT ck_lectures_status CHECK (status IN ('draft', 'open', 'closed'))
);

-- 4. enrollments (수강 권한 판정 기준) ----------------------------------
CREATE TABLE enrollments (
    user_id      NUMBER(19) NOT NULL,
    Lid          NUMBER(19) NOT NULL,
    done         NUMBER(1)  DEFAULT 0 NOT NULL,             -- 수료 여부
    position     NUMBER(10),                                -- 이어보기 위치(초)
    enrolled_at  TIMESTAMP,
    completed_at TIMESTAMP,
    CONSTRAINT pk_enrollments      PRIMARY KEY (user_id, Lid),
    CONSTRAINT fk_enrollments_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_enrollments_lec  FOREIGN KEY (Lid)     REFERENCES lectures (Lid)  ON DELETE CASCADE
);

-- 5. cart (가격은 lectures.Lprice 를 본다) -----------------------------
CREATE TABLE cart (
    user_id NUMBER(19) NOT NULL,
    Lid     NUMBER(19) NOT NULL,
    created TIMESTAMP  DEFAULT SYSTIMESTAMP,
    CONSTRAINT pk_cart      PRIMARY KEY (user_id, Lid),
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_lec  FOREIGN KEY (Lid)     REFERENCES lectures (Lid)  ON DELETE CASCADE
);

-- 6. coupons (orders 보다 먼저: orders.cid 가 참조) ---------------------
--    할인 금액·기한 범위를 DB 가 제한하지 않는다 (의도된 취약점)
CREATE TABLE coupons (
    cid        NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    user_id    NUMBER(19)         NOT NULL,                -- 발행한 강사
    Lid        NUMBER(19),                                 -- NULL = 전체 강의
    cname      VARCHAR2(100 CHAR) NOT NULL,
    code       VARCHAR2(50 CHAR),                          -- 사용자가 입력하는 등록 코드
    discount   NUMBER(10)         NOT NULL,                -- 원
    min_amount NUMBER(10),                                 -- 적용 최소 금액
    quantity   NUMBER(10),                                 -- 발급 가능 총수량. 미확정이면 NULL
    issued     NUMBER(10)         DEFAULT 0 NOT NULL,      -- 실제 발급 수량
    due        TIMESTAMP          NOT NULL,
    created    TIMESTAMP          DEFAULT SYSTIMESTAMP,
    CONSTRAINT pk_coupons      PRIMARY KEY (cid),
    CONSTRAINT fk_coupons_inst FOREIGN KEY (user_id) REFERENCES instructors (user_id),
    CONSTRAINT fk_coupons_lec  FOREIGN KEY (Lid)     REFERENCES lectures (Lid) ON DELETE CASCADE
);

-- 7. user_coupons -----------------------------------------------------
--    cid 는 CASCADE: restrict 면 쿠폰 보유자가 있을 때 강의 강제 삭제가 중간에 실패한다
CREATE TABLE user_coupons (
    user_id     NUMBER(19) NOT NULL,
    cid         NUMBER(19) NOT NULL,
    used        NUMBER(1)  DEFAULT 0 NOT NULL,
    received_at TIMESTAMP,
    used_at     TIMESTAMP,
    CONSTRAINT pk_user_coupons     PRIMARY KEY (user_id, cid),
    CONSTRAINT fk_user_coupons_usr FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_coupons_cpn FOREIGN KEY (cid)     REFERENCES coupons (cid)   ON DELETE CASCADE
);

-- 8. orders (Aprice = order_items.price 합계 - discount) ------------
--    주문당 쿠폰 1장. 강의가 지워져도 주문은 그대로 남는다.
--    포인트 잔액·차감은 결제 계산 정책을 정한 뒤 반영 (ERD 2026-10-13: users.point·orders.use_point 없음)
CREATE TABLE orders (
    oid           NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    ono           VARCHAR2(50 CHAR),                       -- 사용자에게 보여 주는 주문번호
    user_id       NUMBER(19)         NOT NULL,             -- 구매자
    cid           NUMBER(19),                              -- 쓴 쿠폰. 안 썼으면 NULL
    discount      NUMBER(10)         DEFAULT 0 NOT NULL,
    Aprice        NUMBER(10)         NOT NULL,
    pay           VARCHAR2(20 CHAR),
    status        VARCHAR2(20 CHAR)  DEFAULT 'pending' NOT NULL,
    created       TIMESTAMP          DEFAULT SYSTIMESTAMP,
    paid_at       TIMESTAMP,
    cancelled_at  TIMESTAMP,
    refunded_at   TIMESTAMP,
    cancel_reason VARCHAR2(500 CHAR),
    refund_reason VARCHAR2(500 CHAR),
    CONSTRAINT pk_orders        PRIMARY KEY (oid),
    CONSTRAINT fk_orders_user   FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_orders_coupon FOREIGN KEY (cid)     REFERENCES coupons (cid) ON DELETE SET NULL,
    CONSTRAINT ck_orders_status CHECK (status IN ('pending', 'paid', 'cancelled', 'refunded'))
);

-- 9. order_items (거래 기록. 강의가 지워져도 남고 Lid 만 NULL) -----------
CREATE TABLE order_items (
    oiid  NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    oid   NUMBER(19)         NOT NULL,
    Lid   NUMBER(19),                                      -- 강제 삭제되면 NULL
    Lname VARCHAR2(200 CHAR) NOT NULL,                     -- 구매 시점 강의명 스냅샷
    price NUMBER(10)         NOT NULL,                     -- 구매 시점 가격
    CONSTRAINT pk_order_items       PRIMARY KEY (oiid),
    CONSTRAINT fk_order_items_order FOREIGN KEY (oid) REFERENCES orders (oid)   ON DELETE CASCADE,
    CONSTRAINT fk_order_items_lec   FOREIGN KEY (Lid) REFERENCES lectures (Lid) ON DELETE SET NULL
);
-- (oid, Lid) 고유. 일반 복합 UNIQUE 는 한 주문에서 강의 두 개를 지울 때 두 번째 SET NULL 이
-- ORA-00001 로 막히므로, Lid 가 NULL 이면 두 식이 모두 NULL 이 되는 함수 기반 인덱스로 건다.
CREATE UNIQUE INDEX uq_order_items_oid_lid ON order_items (
    CASE WHEN Lid IS NOT NULL THEN oid END,
    CASE WHEN Lid IS NOT NULL THEN Lid END
);

-- 10. settlements -----------------------------------------------------
--     bank·account 는 지급 처리 시점 스냅샷
CREATE TABLE settlements (
    sid           NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    user_id       NUMBER(19)         NOT NULL,             -- 정산 대상 강사
    period        VARCHAR2(7 CHAR)   NOT NULL,             -- 2026.10
    revenue       NUMBER(12)         NOT NULL,
    deduction     NUMBER(12)         DEFAULT 0 NOT NULL,
    amount        NUMBER(12)         NOT NULL,             -- revenue - deduction
    status        VARCHAR2(20 CHAR)  DEFAULT 'requested' NOT NULL,
    requested     TIMESTAMP,
    approved_by   NUMBER(19),                              -- 승인한 관리자
    approved_at   TIMESTAMP,
    rejected_at   TIMESTAMP,
    reject_reason VARCHAR2(500 CHAR),
    paid_at       TIMESTAMP,
    bank          VARCHAR2(50 CHAR),
    account       VARCHAR2(50 CHAR),
    CONSTRAINT pk_settlements        PRIMARY KEY (sid),
    CONSTRAINT uq_settlements_period UNIQUE (user_id, period),
    CONSTRAINT fk_settlements_inst   FOREIGN KEY (user_id)     REFERENCES instructors (user_id),
    CONSTRAINT fk_settlements_admin  FOREIGN KEY (approved_by) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_settlements_status CHECK (status IN ('requested', 'approved', 'rejected', 'paid'))
);

-- 11. assignments (과제는 강의당 1개, 제출은 사용자당 1개) ---------------
CREATE TABLE assignments (
    aid           NUMBER(19)          GENERATED BY DEFAULT AS IDENTITY,
    Lid           NUMBER(19)          NOT NULL,
    user_id       NUMBER(19)          NOT NULL,            -- 제출자
    work          VARCHAR2(500 CHAR),                      -- 제출 파일
    work_filename VARCHAR2(255 CHAR),                      -- 제출 파일 원본 이름
    Wnote         VARCHAR2(1000 CHAR),                     -- 제출 메모
    submitted     TIMESTAMP,
    updated       TIMESTAMP,
    score         NUMBER(3),
    feedback      CLOB,
    feedback_at   TIMESTAMP,
    CONSTRAINT pk_assignments      PRIMARY KEY (aid),
    CONSTRAINT uq_assignments      UNIQUE (Lid, user_id),
    CONSTRAINT fk_assignments_lec  FOREIGN KEY (Lid)     REFERENCES lectures (Lid)   ON DELETE CASCADE,
    CONSTRAINT fk_assignments_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

-- 12. reviews (복합 PK 가 1인 1리뷰를 강제) -----------------------------
CREATE TABLE reviews (
    Lid     NUMBER(19) NOT NULL,
    user_id NUMBER(19) NOT NULL,
    star    NUMBER(1)  NOT NULL,                           -- 1~5 (DB 범위 제한 없음)
    review  CLOB,
    created TIMESTAMP  DEFAULT SYSTIMESTAMP,
    updated TIMESTAMP,
    CONSTRAINT pk_reviews      PRIMARY KEY (Lid, user_id),
    CONSTRAINT fk_reviews_lec  FOREIGN KEY (Lid)     REFERENCES lectures (Lid)   ON DELETE CASCADE,
    CONSTRAINT fk_reviews_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

-- 13. qna (강의 Q&A) --------------------------------------------------
CREATE TABLE qna (
    qid            NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    Lid            NUMBER(19)         NOT NULL,
    user_id        NUMBER(19)         NOT NULL,            -- 질문자
    title          VARCHAR2(200 CHAR) NOT NULL,
    question       CLOB,
    image          VARCHAR2(500 CHAR),                     -- 질문 첨부 이미지 1개
    image_filename VARCHAR2(255 CHAR),
    answer         CLOB,                                   -- NULL = 답변 대기
    answered_by    NUMBER(19),
    answered_at    TIMESTAMP,
    isSecret       NUMBER(1)          DEFAULT 0 NOT NULL,
    created        TIMESTAMP          DEFAULT SYSTIMESTAMP,
    updated        TIMESTAMP,
    CONSTRAINT pk_qna          PRIMARY KEY (qid),
    CONSTRAINT fk_qna_lec      FOREIGN KEY (Lid)         REFERENCES lectures (Lid)   ON DELETE CASCADE,
    CONSTRAINT fk_qna_user     FOREIGN KEY (user_id)     REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_qna_answerer FOREIGN KEY (answered_by) REFERENCES users (user_id) ON DELETE SET NULL
);

-- 14. inquiries (서비스 문의) -----------------------------------------
CREATE TABLE inquiries (
