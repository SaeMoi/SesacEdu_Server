-- =====================================================================
--  schema.sql : 새싹에듀 ERD 16개 테이블 Oracle DDL (ERD 컬럼 보완본 2026-10-13 기준)
--  Target     : AWS RDS for Oracle (19c 이상). 마스터 사용자(또는 앱 사용자) 스키마에 만든다.
--               SYSDBA·테이블스페이스 지정 없음 → 접속한 사용자의 기본 테이블스페이스(RDS: USERS)를 쓴다.
--  실행       : seed.sql 이 맨 앞에서 @@schema.sql 로 부른다. 단독 실행도 된다.
--
--  !! 주의 !! 16개 테이블을 DROP 하고 다시 만든다. 기존 행은 모두 사라진다.
--
--  - DROP 은 PL/SQL 블록으로 '테이블 없음(ORA-00942)'만 무시하므로 19c 에서도 재실행해도 된다.
--    (DROP TABLE IF EXISTS 는 23ai 전용이라 RDS 19c 에서 실패한다)
--  - 명명: 회원 키는 user_id. Lid / cid / oid 등은 ERD 그대로.
--  - ERD 의 lectures.level 은 Oracle 예약어(LEVEL)라 lvl 로 바꿨다.
--  - ERD boolean → NUMBER(1) 0/1, text → CLOB, datetime → TIMESTAMP.
--  - ERD 의 delete: restrict 는 Oracle 기본 동작(절 없음)이다.
--  - email_auth / audit_logs / refresh_tokens 는 ERD 에서 주석(보류) 상태라 만들지 않는다.
--
--  강의 강제 삭제 시 연쇄 (ERD 변경분)
--    cart · assignments · reviews · qna · enrollments 삭제
--    coupons → user_coupons 삭제
--    order_items 는 남고 Lid 만 NULL (Lname 으로 강의명 확인)
-- =====================================================================

-- 0. 기존 테이블 제거 (FK 역순) ------------------------------------------
BEGIN
    FOR t IN (SELECT column_value AS name FROM TABLE(sys.odcivarchar2list(
                  'COMMENTS', 'POSTS', 'INQUIRIES', 'QNA', 'REVIEWS', 'ASSIGNMENTS',
                  'SETTLEMENTS', 'ORDER_ITEMS', 'ORDERS', 'USER_COUPONS', 'COUPONS',
                  'CART', 'ENROLLMENTS', 'LECTURES', 'INSTRUCTORS', 'USERS'))) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || t.name || ' CASCADE CONSTRAINTS PURGE';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN RAISE; END IF;   -- 없는 테이블만 건너뜀
        END;
    END LOOP;
END;
