-- Oracle 12c+; latest ERD, limited to users for this implementation.
CREATE TABLE users (
    user_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    mail VARCHAR2(255 CHAR) NOT NULL,
    pw VARCHAR2(255 CHAR) NOT NULL,
    uname VARCHAR2(50 CHAR) NOT NULL,
    nickname VARCHAR2(50 CHAR) NOT NULL,
    token CLOB,
    phone VARCHAR2(20 CHAR),
    b_date DATE,
    address VARCHAR2(500 CHAR),
    auth NUMBER(1) DEFAULT 0 NOT NULL,
    status VARCHAR2(20 CHAR) DEFAULT 'active' NOT NULL,
    created TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_mail UNIQUE (mail),
    CONSTRAINT ck_users_auth CHECK (auth IN (0, 1, 2, 3, 4)),
    CONSTRAINT ck_users_status CHECK (status IN ('active', 'restricted'))
);
-- nickname uniqueness remains an application check, per the signup API.
-- No last_login_* columns, email_auth, audit_logs or refresh_tokens tables.
