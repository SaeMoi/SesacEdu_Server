CREATE TABLE IF NOT EXISTS users (
    user_id       NUMBER(19)         GENERATED BY DEFAULT AS IDENTITY,
    mail          VARCHAR2(255 CHAR) NOT NULL,
    pw            VARCHAR2(255 CHAR) NOT NULL,             -- MD5 hex (의도된 취약점)
    uname         VARCHAR2(50 CHAR)  NOT NULL,
    nickname      VARCHAR2(50 CHAR)  NOT NULL,             -- UNIQUE 없음 (앱 검사만)
    phone         VARCHAR2(11 CHAR),
    b_date        DATE,
    address       VARCHAR2(500 CHAR),
    auth          NUMBER(1)          DEFAULT 0 NOT NULL,   -- 0 일반/1 수강생/2 강사/3 관리자/4 강사 신청 대기
    status        VARCHAR2(20 CHAR)  DEFAULT 'active' NOT NULL,
    profile_image VARCHAR2(255 CHAR),                      -- {user_id}_profile.png
    point         NUMBER             DEFAULT 0,            -- 단일 컬럼 (원장 없음 = 의도된 약점)
    created       TIMESTAMP          DEFAULT SYSTIMESTAMP NOT NULL,
    last_login_at TIMESTAMP,
    last_login_ip VARCHAR2(45 CHAR),
    CONSTRAINT pk_users        PRIMARY KEY (user_id),
    CONSTRAINT uq_users_mail   UNIQUE (mail),
    CONSTRAINT ck_users_auth   CHECK (auth IN (0, 1, 2, 3, 4)),
    CONSTRAINT ck_users_status CHECK (status IN ('active', 'restricted'))
);

