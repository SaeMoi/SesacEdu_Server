-- 커뮤니티(/forum) 테스트용 (2026-10-15). 컬럼은 db/schema.sql과 같다.
-- comments.pid → posts.pid만 ON DELETE CASCADE (글 삭제 시 댓글 함께 삭제를 실제 DB처럼 확인). users FK는 두지 않는다.
CREATE TABLE IF NOT EXISTS posts (
    pid NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    category VARCHAR2(50),
    title VARCHAR2(200) NOT NULL,
    content CLOB,
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated TIMESTAMP
);
CREATE TABLE IF NOT EXISTS comments (
    cmid NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pid NUMBER(19) NOT NULL,
    user_id NUMBER(19) NOT NULL,
    content CLOB,
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated TIMESTAMP,
    CONSTRAINT fk_comments_post FOREIGN KEY (pid) REFERENCES posts (pid) ON DELETE CASCADE
);

