CREATE TABLE IF NOT EXISTS users (
    user_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mail VARCHAR2(255) NOT NULL UNIQUE,
    pw VARCHAR2(255) NOT NULL,
    uname VARCHAR2(50) NOT NULL,
    nickname VARCHAR2(50) NOT NULL,
    token CLOB,
    phone VARCHAR2(20),
    b_date DATE,
    address VARCHAR2(500),
    picture VARCHAR2(500),
    alarm NUMBER(1),
    auth NUMBER(1) DEFAULT 0 NOT NULL CHECK (auth IN (0,1,2,3,4)),
    status VARCHAR2(20) DEFAULT 'active' NOT NULL CHECK (status IN ('active','restricted')),
    created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated TIMESTAMP,
    point NUMBER(19) DEFAULT 0 NOT NULL         -- 포인트 잔액 (add_points.sql, Kim 2026-10-19)
);

